"""Deal Workspace API: truthful timeline from persisted CRM and work evidence.

All reads require deal ACL; manual notes never imply a verified call/email.
No external connector data is fetched. Pagination remains a future hardening step.
"""
import json
from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, ConfigDict, Field
from sqlalchemy import select
from sqlalchemy.orm import Session
from .access import readable_record, visible_record_condition
from .auth import principal, record_audit, uid, aware
from .db import get_db
from .models import (CRMRecord, CRMLink, DealNote, Audit, User,
                     WorkItem, WorkResult, CommercialSignal)
from .relationships import lock_tenant_crm

router=APIRouter(prefix='/api/v1/deals', tags=['Deal Workspace'])

class NoteIn(BaseModel):
 model_config=ConfigDict(extra='forbid',str_strip_whitespace=True)
 text:str=Field(min_length=2,max_length=3000)
 idem:str=Field(min_length=8,max_length=120,pattern=r'^[A-Za-z0-9_-]+$')

def deal_or_404(db:Session,user:User,deal_id:str)->CRMRecord:
 deal=readable_record(db,user,deal_id)
 if not deal or deal.kind!='deals':
  raise HTTPException(404,'Oportunidad no accesible')
 return deal

def note_out(note,author=None):
 return {'id':note.id,'deal_id':note.deal_id,'text':note.body,
         'author':author,'at':aware(note.created_at).isoformat(),
         'source':'deal_notes','verification':'user_attested'}

@router.post('/{deal_id}/notes')
def add_note(deal_id:str,item:NoteIn,db:Session=Depends(get_db),
             user:User=Depends(principal)):
 deal_or_404(db,user,deal_id)
 lock_tenant_crm(db,user.tenant_id)
 previous=db.scalar(select(DealNote).where(
  DealNote.tenant_id==user.tenant_id,DealNote.author_id==user.id,
  DealNote.idem==item.idem))
 if previous:
  if previous.deal_id!=deal_id or previous.body!=item.text:
   raise HTTPException(409,'Clave de operación usada para una nota distinta')
  return {'note':note_out(previous,user.username),'already_recorded':True}
 note=DealNote(id=uid(),tenant_id=user.tenant_id,deal_id=deal_id,
               author_id=user.id,idem=item.idem,body=item.text)
 db.add(note)
 record_audit(db,user,'deal.note.create',note.id,
              {'deal_id':deal_id,'chars':len(item.text)})
 db.flush()
 # Serialize the response before COMMIT: SET LOCAL tenant context expires
 # at the transaction boundary and a post-commit refresh would violate RLS.
 response=note_out(note,user.username)
 db.commit()
 return {'note':response,'already_recorded':False}

@router.get('/{deal_id}/timeline')
def timeline(deal_id:str,db:Session=Depends(get_db),
             user:User=Depends(principal)):
 deal=deal_or_404(db,user,deal_id)
 events=[]
 def add(kind,headline,body,when,source,verification,actor='',event_id='',related_id=None):
  events.append({'id':event_id,'kind':kind,'headline':headline,'body':body or '',
   'at':aware(when).isoformat(),'source':source,
   'verification':verification,'actor':actor,'related_id':related_id})
 add('created','Oportunidad registrada',deal.name,deal.created_at,
     'crm_records','imported_or_manual',event_id='deal:'+deal.id)
 notes=db.scalars(select(DealNote).where(
  DealNote.tenant_id==user.tenant_id,DealNote.deal_id==deal_id
 ).order_by(DealNote.created_at.desc(),DealNote.id.desc()).limit(101)).all()
 changes=db.scalars(select(Audit).where(
  Audit.tenant_id==user.tenant_id,Audit.target==deal_id,
  Audit.action=='pipeline.deal.move'
 ).order_by(Audit.created_at.desc(),Audit.id.desc()).limit(101)).all()
 tasks_q=select(WorkItem).where(WorkItem.tenant_id==user.tenant_id,
  WorkItem.record_id==deal_id)
 if user.role!='admin':tasks_q=tasks_q.where(WorkItem.owner_id==user.id)
 tasks=db.scalars(tasks_q.order_by(
  WorkItem.created_at.desc(),WorkItem.id.desc()).limit(101)).all()
 task_ids=[task.id for task in tasks]
 # Creation audit records identify the actor who scheduled a task; a task
 # without this record may originate from a follow-up generated by completion.
 created_audits=[]
 if task_ids:
  created_audits=db.scalars(select(Audit).where(
   Audit.tenant_id==user.tenant_id,
   Audit.action=='task.create',Audit.target.in_(task_ids)
  ).order_by(Audit.created_at.desc(),Audit.id.desc()).limit(101)).all()
 created_by={entry.target:entry.user_id for entry in created_audits}
 # Replan receipts target the deal, not the task: only expose events for
 # tasks already authorized to this viewer (never another rep's work).
 replan_audits=db.scalars(select(Audit).where(
  Audit.tenant_id==user.tenant_id,Audit.target==deal_id,
  Audit.action=='task.replan'
 ).order_by(Audit.created_at.desc(),Audit.id.desc()).limit(201)).all()
 results=[]
 if task_ids:
  results=db.scalars(select(WorkResult).where(
   WorkResult.tenant_id==user.tenant_id,WorkResult.task_id.in_(task_ids)
  ).order_by(WorkResult.created_at.desc(),WorkResult.id.desc()).limit(101)).all()
 signals=db.scalars(select(CommercialSignal).where(
  CommercialSignal.tenant_id==user.tenant_id,
  CommercialSignal.record_id==deal_id,
  CommercialSignal.source_type=='manual_report'
 ).order_by(CommercialSignal.recorded_at.desc(),CommercialSignal.id.desc()).limit(101)).all()
 actor_ids={x.author_id for x in notes}|{x.user_id for x in changes}|{
  x.owner_id for x in tasks}|{x.actor_id for x in signals}|{
  x.user_id for x in created_audits}|{x.user_id for x in replan_audits}
 authors={}
 if actor_ids:
  authors={row.id:row.username for row in db.scalars(select(User).where(
    User.tenant_id==user.tenant_id,User.id.in_(actor_ids))).all()}
 for note in notes[:100]:
  add('note','Nota añadida',note.body,note.created_at,'deal_notes',
      'user_attested',authors.get(note.author_id,''),note.id)
 for change in changes[:100]:
  try:detail=json.loads(change.detail or '{}')
  except (ValueError,TypeError):detail={}
  before=str(detail.get('from') or 'Sin etapa')
  after=str(detail.get('to') or 'Sin etapa')
  add('stage','Etapa modificada',before+' → '+after,change.created_at,
      'audit_events','recorded_action',authors.get(change.user_id,''),change.id)
 for task in tasks[:100]:
  creator=created_by.get(task.id)
  is_own=creator==task.owner_id
  headline=('Tarea propia programada: ' if is_own else
            'Tarea asignada: ' if creator else
            'Seguimiento programado: ')+task.title
  add('task',headline,
      'Responsable: '+authors.get(task.owner_id,'Sin identificar')+
      ' · Estado: '+task.state+
      ' · Vence: '+aware(task.due_at).isoformat(),
      task.created_at,'work_items','planned_not_executed',
      authors.get(creator,'Sistema / seguimiento'),task.id,related_id=task.id)
 visible_task_ids=set(task_ids)
 for change in replan_audits:
  try: detail=json.loads(change.detail or '{}')
  except (ValueError,TypeError):continue
  task_id=detail.get('task_id')
  if task_id not in visible_task_ids:continue
  before=detail.get('from')
  after=detail.get('to')
  if not isinstance(before,str) or not isinstance(after,str):continue
  add('reschedule','Tarea reprogramada: '+str(detail.get('title') or ''),
      before+' → '+after,change.created_at,
      'audit_events','recorded_change',authors.get(change.user_id,''),
      change.id,related_id=task_id)
 for result in results[:100]:
  add('result','Resultado comercial declarado: '+result.outcome,
      result.note,result.created_at,'work_results','user_reported_result',
      authors.get(result.owner_id,''),result.id)
 for signal in signals[:100]:
  label='Señal declarada: '+signal.kind
  add('signal',label,signal.detail,signal.recorded_at,
      'commercial_signals','user_attested'+(' (corregida)' if signal.status!='current' else ''),
      authors.get(signal.actor_id,''),signal.id)
 # Imported activities appear only if directly linked AND individually visible.
 # A link alone must never bypass the rep's RecordGrant.
 activity_ids=db.scalars(select(CRMLink.record_id).where(
  CRMLink.tenant_id==user.tenant_id,
  CRMLink.related_id==deal_id).limit(201)).all()
 activities=[]
 if activity_ids:
  activities=db.scalars(select(CRMRecord).where(
   visible_record_condition(user),CRMRecord.kind=='activities',
   CRMRecord.id.in_(activity_ids)).order_by(
   CRMRecord.created_at.desc(),CRMRecord.id.desc()).limit(101)).all()
 for activity in activities[:100]:
  add('imported_activity','Actividad CRM importada',activity.name,
      activity.created_at,'crm_records','imported_unverified',
      event_id='activity:'+activity.id,related_id=activity.id)
 events.sort(key=lambda e:(e['at'],e['id']),reverse=True)
 truncated=(len(events)>100 or any(len(group)>100 for group in
  (notes,changes,tasks,results,signals,activities)) or
  len(replan_audits)>200 or len(activity_ids)>200)
 return {'deal_id':deal_id,'events':events[:100],
         'truncated':truncated,
         'sources':['crm_records','deal_notes','audit_events','work_items',
                    'work_results','commercial_signals']}
