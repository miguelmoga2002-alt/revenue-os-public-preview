"""Browser-facing HTTP defenses without trusting unverified proxy headers.

- SHA-256 script allowlists support existing static inline JavaScript without
  unsafe-inline or unsafe-eval; the policy must be updated as UI files change.
- Cross-site browser Origin requests cannot mutate application state.
- HTTPS transport/HSTS belongs at TLS termination; HSTS is also emitted on
  HTTPS connections as defense in depth.
"""
import base64
import hashlib
import os
import re
from pathlib import Path
from urllib.parse import urlparse

from fastapi import HTTPException

WEB_ROOT=Path(__file__).resolve().parents[1]/"web"
PAGES={'/':'index.html','/focus':'focus.html','/crm':'crm.html'}
DEAL_PATH=re.compile(r'\A/deals/[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}\Z')
SCRIPT_PATTERN=re.compile(rb'<script\b[^>]*>(.*?)</script\s*>',re.I|re.S)
HASHES={}

def script_hashes(page):
 raw=(WEB_ROOT/page).read_bytes()
 scripts=SCRIPT_PATTERN.findall(raw)
 if len(scripts)!=1:
  raise RuntimeError("Unexpected script count in "+page+"; review CSP")
 # HTML parsers normalize CRLF/CR to LF before evaluating inline scripts.
 # Git on Windows can check out CRLF, so hash the bytes the browser sees.
 return ["'sha256-"+base64.b64encode(hashlib.sha256(source.replace(b'\r\n',b'\n').replace(b'\r',b'\n')).digest()).decode('ascii')+"'" for source in scripts]

def policy(path):
 if path in PAGES:
  hashes=script_hashes(PAGES[path])
 elif DEAL_PATH.fullmatch(path):
  hashes=script_hashes('crm.html')
 elif path=="/api/v1/oauth/callback":
  # Controlled OAuth callback has one fixed inline script generated by
  # crm_oauth.callback; explicitly hash exactly those bytes at runtime.
  from .crm_oauth import callback
  html=callback().body
  scripts=SCRIPT_PATTERN.findall(html)
  if len(scripts)!=1:raise RuntimeError("OAuth callback script changed")
  hashes=["'sha256-"+base64.b64encode(hashlib.sha256(scripts[0]).digest()).decode('ascii')+"'"]
 else:
  return None
 return ("default-src 'none'; base-uri 'none'; object-src 'none'; "
         "form-action 'self'; frame-ancestors 'none'; "
         "script-src 'self' "+' '.join(hashes)+"; "
         "style-src 'self' 'unsafe-inline'; "
         "img-src 'self' data:; font-src 'self'; "
         "connect-src 'self'; upgrade-insecure-requests")

def allowed_browser_origin(request):
 origin=request.headers.get('origin')
 if not origin:return True
 parsed=urlparse(origin)
 if parsed.scheme not in ('http','https') or not parsed.hostname or parsed.username or parsed.password:
  return False
 # Require explicitly declared external origin when deployed behind a reverse
 # proxy; do not trust X-Forwarded-Host or X-Forwarded-Proto from public input.
 expected=os.getenv('REVENUE_OS_PUBLIC_ORIGIN','').rstrip('/')
 if expected:
  return origin==expected
 return origin==str(request.base_url).rstrip('/')

def enforce_origin(request):
 if request.method not in ('POST','PUT','PATCH','DELETE'):return
 # OAuth provider redirects return a GET callback. Same-origin requests
 # without an Origin are valid for CLI/API clients using Bearer tokens.
 if not allowed_browser_origin(request):
  raise HTTPException(403,'Origen de solicitud no permitido')
